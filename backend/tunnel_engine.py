"""Tunnel engine discovery and Windows tunnel-service control.

Drives an installed AmneziaWG (preferred) or stock WireGuard client's
tunnel service: `amneziawg /installtunnelservice <conf>` creates the
service `AmneziaWGTunnel$<name>` (same shape for wireguard.exe /
`WireGuardTunnel$<name>`). Configs generated by wireguard_config.py use
WARP-safe identity params, so both engines speak to Cloudflare's edge.
Reference: run evidence/research-amneziawg.md (enterprise.md deployment).
"""

from __future__ import annotations

import os
import shutil
import subprocess
from typing import NamedTuple

CONF_NAME = "pywarp-warp"

_ENGINE_CANDIDATES = {
    "AmneziaWG": (
        "AmneziaWGTunnel$",
        ("amneziawg.exe", "C:/Program Files/AmneziaWG/amneziawg.exe"),
    ),
    "WireGuard": (
        "WireGuardTunnel$",
        ("wireguard.exe", "C:/Program Files/WireGuard/wireguard.exe"),
    ),
}


class EngineError(Exception):
    """A tunnel-service operation failed."""


class Engine(NamedTuple):
    name: str
    exe_path: str
    service_prefix: str


def service_name(engine: Engine) -> str:
    return f"{engine.service_prefix}{CONF_NAME}"


def find_engine_from_paths(
    amneziawg_path: str | None,
    wireguard_path: str | None,
) -> Engine | None:
    if amneziawg_path:
        prefix, _ = _ENGINE_CANDIDATES["AmneziaWG"]
        return Engine("AmneziaWG", amneziawg_path, prefix)
    if wireguard_path:
        prefix, _ = _ENGINE_CANDIDATES["WireGuard"]
        return Engine("WireGuard", wireguard_path, prefix)
    return None


def _locate(candidate: tuple[str, str]) -> str | None:
    on_path, installed = candidate
    found = shutil.which(on_path)
    return found or (installed if os.path.isfile(installed) else None)


def find_tunnel_engine() -> Engine | None:
    """Prefer AmneziaWG (obfuscation-capable), fall back to stock WireGuard."""
    awg = _locate(_ENGINE_CANDIDATES["AmneziaWG"][1])
    wg = _locate(_ENGINE_CANDIDATES["WireGuard"][1])
    return find_engine_from_paths(awg, wg)


def _run(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        args,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
        creationflags=(
            subprocess.CREATE_NO_WINDOW
            if hasattr(subprocess, "CREATE_NO_WINDOW")
            else 0
        ),
    )


def install_tunnel(engine: Engine, conf_path: str) -> None:
    result = _run([engine.exe_path, "/installtunnelservice", conf_path])
    if result.returncode != 0:
        raise EngineError(
            result.stderr.strip()
            or result.stdout.strip()
            or f"{engine.name} tunnel service install failed"
        )


def remove_tunnel(engine: Engine) -> None:
    """Remove the tunnel service.

    The CLI takes the TUNNEL name here (it derives the service name itself)
    and forbids '$' in tunnel names, so the service name must NOT be passed.
    A missing tunnel is treated as success (idempotent removal).
    """
    result = _run([engine.exe_path, "/uninstalltunnelservice", CONF_NAME])
    if result.returncode != 0:
        combined = ((result.stderr or "") + (result.stdout or "")).lower()
        if any(
            marker in combined
            for marker in ("does not exist", "not found", "no such", "unable to find")
        ):
            return
        raise EngineError(
            result.stderr.strip()
            or result.stdout.strip()
            or f"{engine.name} tunnel service removal failed"
        )


def tunnel_service_running(engine: Engine) -> bool:
    result = _run(["sc", "query", service_name(engine)])
    return result.returncode == 0 and "RUNNING" in (result.stdout or "").upper()
